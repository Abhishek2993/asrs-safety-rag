"""Trend summaries for a filtered set of reports, with cited evidence.

A summary has two parts that are produced differently on purpose:

* **Statistics** (counts per year, top labels, top primary problems,
  anomalies) are computed deterministically with pandas. Numbers are never
  generated by the LLM.
* **Narrative findings** are written by the LLM from a small evidence set of
  reports (ACN, date, phase, aircraft, synopsis). Each statement must cite
  ACNs from that evidence set; :mod:`asrs_rag.cite` checks and enforces this.
  Without an LLM a template writes one cited finding per top label.
"""

from __future__ import annotations

import logging
from collections import Counter
from dataclasses import asdict, dataclass, field

import pandas as pd

from asrs_rag.cite import check_citations, enforce_citations
from asrs_rag.index import ReportIndex
from asrs_rag.labels import LABELS
from asrs_rag.llm import LLMError
from asrs_rag.retrieve import Filters, HybridRetriever

log = logging.getLogger(__name__)

SUMMARY_SYSTEM = (
    "You are an aviation safety analyst. You summarise recurring patterns across "
    "NASA ASRS incident reports for a safety review. You never assign blame and you "
    "only state what the provided reports say."
)


@dataclass
class TrendSummary:
    """Everything shown for a trend query."""

    filters: dict
    n_reports: int
    counts_by_year: dict[int, int]
    label_counts: dict[str, int]
    label_by_year: dict[int, dict[str, int]]
    top_primary_problems: list[tuple[str, int]]
    top_anomalies: list[tuple[str, int]]
    evidence: list[dict] = field(default_factory=list)
    generator: str = "template"
    raw_text: str = ""
    text: str = ""
    removed_statements: list[str] = field(default_factory=list)
    citation_check: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        """JSON-friendly representation."""
        return asdict(self)


def compute_statistics(reports: pd.DataFrame) -> dict:
    """Deterministic counts used by both the summary text and the charts."""
    by_year = reports.groupby("year").size().sort_index()
    label_counts = Counter(lab for labs in reports["labels"] for lab in labs)
    label_by_year: dict[int, dict[str, int]] = {}
    for year, grp in reports.groupby("year"):
        c = Counter(lab for labs in grp["labels"] for lab in labs)
        label_by_year[int(year)] = {lab: int(c.get(lab, 0)) for lab in LABELS}
    anomalies = Counter(
        a.split(" ")[0] + " " + " ".join(a.split(" ")[1:3]) for an in reports["anomaly"] for a in an
    )
    problems = Counter(p for p in reports["primary_problem"] if p)
    return {
        "n_reports": len(reports),
        "counts_by_year": {int(k): int(v) for k, v in by_year.items()},
        "label_counts": {lab: int(label_counts.get(lab, 0)) for lab in LABELS},
        "label_by_year": label_by_year,
        "top_primary_problems": problems.most_common(6),
        "top_anomalies": anomalies.most_common(6),
    }


def select_evidence(
    index: ReportIndex,
    filters: Filters,
    n: int = 12,
    query: str | None = None,
) -> list[dict]:
    """Choose the reports the summary may cite.

    With a ``query`` the most relevant matching reports are used (hybrid
    retrieval). Otherwise the evidence is spread over the most frequent labels:
    the most recent reports for each top label, round-robin, so the summary
    reflects the main factors rather than an arbitrary sample.
    """
    if query:
        hits = HybridRetriever(index).search(query, k=n, filters=filters)
        rows = [h.report for h in hits]
    else:
        subset = index.reports[filters.mask(index.reports)]
        subset = subset.sort_values(["date", "acn"], ascending=[False, True])
        counts = Counter(lab for labs in subset["labels"] for lab in labs)
        queues = {
            lab: [r for r in subset.to_dict("records") if lab in r["labels"]]
            for lab, _ in counts.most_common()
        }
        rows, seen = [], set()
        while len(rows) < n and any(queues.values()):
            for lab in list(queues):
                while queues[lab] and queues[lab][0]["acn"] in seen:
                    queues[lab].pop(0)
                if queues[lab] and len(rows) < n:
                    r = queues[lab].pop(0)
                    rows.append(r)
                    seen.add(r["acn"])
    return [
        {
            "acn": r["acn"],
            "date": str(r["date"])[:7],
            "flight_phase": "; ".join(r["flight_phase"]),
            "aircraft_type": r["aircraft_type"],
            "labels": list(r["labels"]),
            "synopsis": r["synopsis"],
            "narrative": r["narrative_clean"],
        }
        for r in rows
    ]


def build_summary_prompt(description: str, evidence: list[dict], n_bullets: int = 5) -> str:
    """Prompt asking for cited qualitative findings (no numbers)."""
    lines = [
        f"Filter: {description}",
        "",
        "Reports (cite them by ACN):",
    ]
    for e in evidence:
        lines.append(
            f"[ACN {e['acn']}] {e['date']} | {e['flight_phase']} | {e['aircraft_type']}: "
            f"{e['synopsis']}"
        )
    lines += [
        "",
        f"Write {n_bullets} bullet points describing recurring safety patterns in these "
        "reports (causes, conditions, consequences).",
        "Rules:",
        "- Start every bullet with '- '.",
        "- End every bullet with the ACNs that support it, like [ACN 1234567, 7654321].",
        "- Cite only ACNs from the list above. Do not invent ACNs.",
        "- Do not state counts or percentages; they are computed separately.",
        "- Do not speculate beyond what the reports say and do not assign blame.",
    ]
    return "\n".join(lines)


def template_summary(stats: dict, evidence: list[dict], max_items: int = 5) -> str:
    """No-LLM findings: one cited statement per frequent label."""
    n = stats["n_reports"] or 1
    lines = []
    ranked = sorted(stats["label_counts"].items(), key=lambda t: -t[1])
    for lab, count in ranked:
        if count == 0 or len(lines) >= max_items:
            break
        examples = [e["acn"] for e in evidence if lab in e["labels"]][:3]
        if not examples:
            continue
        cites = ", ".join(f"ACN {a}" for a in examples)
        lines.append(
            f"- {lab.replace('_', ' ').capitalize()} was coded as a contributing factor in "
            f"{count} of {stats['n_reports']} reports ({count / n:.0%}); examples [{cites}]"
        )
    return "\n".join(lines)


def describe_filters(f: Filters) -> str:
    """Human-readable filter description."""
    parts = []
    if f.phases:
        parts.append(f"flight phase contains {', '.join(f.phases)}")
    if f.year_from or f.year_to:
        parts.append(f"years {f.year_from or 'start'}-{f.year_to or 'end'}")
    if f.labels:
        parts.append(f"factor {', '.join(f.labels)}")
    if f.primary_problems:
        parts.append(f"primary problem {', '.join(f.primary_problems)}")
    if f.aircraft:
        parts.append(f"aircraft {f.aircraft}")
    return "; ".join(parts) or "all reports"


def summarise(
    index: ReportIndex,
    filters: Filters | None = None,
    llm=None,
    query: str | None = None,
    n_evidence: int = 12,
    enforce: bool = True,
) -> TrendSummary:
    """Compute statistics and a cited summary for the reports matching ``filters``."""
    filters = filters or Filters()
    subset = index.reports[filters.mask(index.reports)]
    stats = compute_statistics(subset)
    evidence = select_evidence(index, filters, n_evidence, query) if len(subset) else []
    allowed = {e["acn"] for e in evidence}
    sources = {e["acn"]: f"{e['synopsis']} {e['narrative']}" for e in evidence}

    generator, raw = "template", ""
    if llm is not None and evidence:
        try:
            raw = llm.generate(
                build_summary_prompt(describe_filters(filters), evidence),
                system=SUMMARY_SYSTEM,
                max_tokens=600,
            )
            generator = getattr(llm, "name", "llm")
        except LLMError as exc:
            log.warning("LLM failed (%s); falling back to template summary", exc)
    if generator == "template":
        raw = template_summary(stats, evidence)

    check = check_citations(raw, allowed, sources)
    text, removed = enforce_citations(raw, allowed) if enforce else (raw, [])
    return TrendSummary(
        filters={k: (sorted(v) if isinstance(v, set) else v) for k, v in asdict(filters).items()},
        evidence=evidence,
        generator=generator,
        raw_text=raw,
        text=text,
        removed_statements=removed,
        citation_check=check.to_dict(),
        **stats,
    )
